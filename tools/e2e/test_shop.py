    check("Krämvit" in page.locator("#p-jfk-hoodie [data-shop-chosen]").inner_text(), "vald färg visas")
    g = page.locator('#p-jfk-hoodie [data-shop-drawing]').evaluate("e => getComputedStyle(e).getPropertyValue('--g').trim()")
