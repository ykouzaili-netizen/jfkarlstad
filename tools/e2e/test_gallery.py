def photo(name: str, taken: str | None, color, size=(1600, 1200)) -> str:
    """Ett "foto" med motiv: färgtoning och former som beror på namnet, så att olika bilder får olika bildavtryck."""
    import random
    rnd = random.Random(name)
    w, h = size
    img = Image.new("RGB", size, color)
    d = ImageDraw.Draw(img)
    for y in range(0, h, 8):
        t = y / h
        d.rectangle([0, y, w, y + 8], fill=tuple(int(c * (0.4 + 0.6 * t)) for c in color))
    for _ in range(14):
        x0, y0 = rnd.randrange(w), rnd.randrange(h)
        r = rnd.randrange(w // 12, w // 3)
        shade = tuple(rnd.randrange(256) for _ in range(3))
        (d.ellipse if rnd.random() < 0.5 else d.rectangle)([x0 - r, y0 - r // 2, x0 + r, y0 + r // 2], fill=shade)
    d.text((40, 40), name, fill=(255, 255, 255))
    path = D / name
    if taken:
        ex = Image.Exif()
        ex[0x0110] = "Testkamera"
        ex.get_ifd(0x8769)[0x9003] = taken
        img.save(path, "JPEG", quality=85, exif=ex)
    else:
        img.save(path, "JPEG", quality=85)
    return str(path)


